export function companyFor(domain: string): SeedCompany {
  const found = SEED_COMPANIES.find((c) => c.domain === domain);
  if (found) return found;
  const contact = SEED_CONTACTS.find((c) => c.website.includes(domain));
  return {
    domain,
    name: contact?.company ?? domain,
    industry: contact?.industry ?? "B2B",
    description: `${contact?.company ?? domain} is a ${contact?.industry ?? "B2B"} company based in ${contact?.location ?? "the US"}.`,
    size: "11-50",
    services: [contact?.industry ?? "Professional services"],
    pain: [
      {
        hypothesis: "Website explains what they do, not the business outcome a buyer gets in 90 days.",
        evidence: "Homepage copy is category-generic; no quantified case study above the fold.",
        severity: "medium",
        category: "marketing",
      },
    ],
    signals: ["Recently refreshed homepage"],
    tech: ["WordPress"],
  };
}

